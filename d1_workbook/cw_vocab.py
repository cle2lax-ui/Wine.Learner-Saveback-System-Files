def pool(chapters, current=None, common=True):
    """[(WORD, clue)] for the given chapters (plus the short common words); duplicates dropped, later chapters\u2019 clues win."""
    d = {}
    for n in ([0] if common else []) + list(chapters):
        for line in V.get(n, []):
            w, cl = line.split("|", 1)
            d[w.strip().upper()] = (w.strip().upper(), cl.strip())
    cur = set()
    if current:
        for n in current:
            for line in V.get(n, []):
                cur.add(line.split("|", 1)[0].strip().upper())
    return list(d.values()), cur



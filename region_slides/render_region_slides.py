class _Measure:
    """A no-op stand-in for ImageDraw, used only to measure row heights. It draws nothing, so the legibility audit (which hooks every real
    text draw and samples the finished image) never sees the measuring pass."""

    def textbbox(self, xy, t, font=None, **kw):
        return font.getbbox(t)

    def textlength(self, t, font=None, **kw):
        return font.getlength(t)

    def text(self, *a, **kw):
        return None


_scratch = _Measure()


def row_height(lead, body):
    return core.run_in(_scratch, (0, 0), lead, body, COLW, PAL, lead_size=LEAD, body_size=BODY, leading=LEADING)


def header(d, x, y, label):
    kf = core.font("kicker_bold", 38)
    core.tracked_text(d, (x, y), label, kf, BURG, tracking=4)
    y += sum(kf.getmetrics()) + 4
    d.line([(x, y), (x + COLW, y)], fill=(190, 170, 150), width=3)
    return y + 18


def banner(img, d, title):
    bh = 150
    d.rectangle([0, 0, CW, bh], fill=(74, 20, 26))
    icon = Image.open(f"{PHOTO_DIR}/QS_glass_icon.png").convert("RGBA")
    ih = 92
    iw = int(ih * icon.size[0] / icon.size[1])
    img.paste(icon.resize((iw, ih), Image.LANCZOS), (M, (bh - ih) // 2), icon.resize((iw, ih), Image.LANCZOS))
    tf = core.font("display_bold", 84)
    d.text((M + iw + 34, (bh - sum(tf.getmetrics())) // 2 - 2), title, font=tf, fill=(255, 255, 255))
    kf = core.font("kicker_bold", 34)
    lab = "HOW IT'S UNIQUE  \u00b7  HOW IT SHOWS UP IN THE GLASS"
    w = sum(core.text_w(d, ch, kf) + 4 for ch in lab)
    core.tracked_text(d, (CW - M - w, (bh - sum(kf.getmetrics())) // 2), lab, kf, core.legible(GOLD, (74, 20, 26), 4.5), tracking=4)
    return bh


def build_slide(idx, sl):
    img = Image.new("RGB", (CW, CH), BG)
    d = ImageDraw.Draw(img)
    bh = banner(img, d, sl["title"])
    regs = sl["regions"]
    PH = 600
    top = bh + 30
    # measure so the rows align across the three columns
    uh = [max(row_height(UNIQUE_LABELS[i], r["unique"][i]) for r in regs) for i in range(4)]
    gh = [max(row_height(r["glass"][j][0], r["glass"][j][1]) for r in regs) for j in range(3)]
    bottom = 0
    for k, r in enumerate(regs):
        x = M + k * (COLW + GAP)
        ph = Image.open(f"{PHOTO_DIR}/{r['photo']}.jpg").convert("RGB")
        tile = core.cover_fit(ph, COLW, PH, y_anchor=r["anchor"])
        # a soft dark foot on the photo carries the region name and its grapes (they sit on the photo to save a block of vertical space)
        shade = Image.new("RGBA", (COLW, PH), (0, 0, 0, 0))
        sd = ImageDraw.Draw(shade)
        for yy in range(PH):
            t = max(0.0, (yy - PH * 0.22) / (PH * 0.78))
            sd.line([(0, yy), (COLW, yy)], fill=(0, 0, 0, int(238 * (t ** 0.78))))
        tile = tile.convert("RGBA")
        tile.alpha_composite(shade)
        img.paste(tile.convert("RGB"), (x, top))
        d = ImageDraw.Draw(img)
        nf_size = 86
        while True:
            nf = core.font("display_black", nf_size)
            if core.text_w(d, r["name"], nf) <= COLW - 44 or nf_size <= 60:
                break
            nf_size -= 2
        tf = core.font("kicker_bold", 32)
        n_h, t_h = sum(nf.getmetrics()), sum(tf.getmetrics())
        ty = top + PH - 24 - t_h
        core.tracked_text(d, (x + 24, ty), r["tag"], tf, (240, 214, 150), tracking=3)
        d.text((x + 24, ty - 6 - n_h), r["name"], font=nf, fill=(255, 255, 255))
        y = top + PH + 22
        y = header(d, x, y, "HOW IT'S UNIQUE")
        for i in range(4):
            core.run_in(d, (x, y), UNIQUE_LABELS[i], r["unique"][i], COLW, PAL, lead_size=LEAD, body_size=BODY, leading=LEADING)
            y += uh[i] + ROWGAP
        y += 6
        y = header(d, x, y, "IN THE GLASS")
        for j in range(3):
            core.run_in(d, (x, y), r["glass"][j][0], r["glass"][j][1], COLW, PAL, lead_size=LEAD, body_size=BODY, leading=LEADING)
            y += gh[j] + ROWGAP
        bottom = max(bottom, y)
    sf = core.font("body", 28)
    foot_y = CH - 84
    if bottom > foot_y - 6:
        raise ValueError(f"slide {idx}: content ends at {bottom}, which runs into the footer at {foot_y}; cut copy")
    d.text((M, foot_y), sl["source"], font=sf, fill=MUTED)
    d.text((M, foot_y + 38), sl["credit"], font=sf, fill=MUTED)
    nm = f"{idx} / {len(SLIDES)}"
    d.text((CW - M - core.text_w(d, nm, sf), foot_y + 19), nm, font=sf, fill=MUTED)
    print(f"  slide {idx}: content ends at {bottom} of {foot_y} (footer); rows unique {uh} glass {gh}")
    return img


def build():
    imgs = []
    for i, sl in enumerate(SLIDES, start=1):
        im = build_slide(i, sl)
        im.save(f"{OUT}/slide_{i}.png")
        imgs.append(im.convert("RGB"))
    pdf = f"{OUT}/Region_Comparison_Slides.pdf"
    imgs[0].save(pdf, "PDF", save_all=True, append_images=imgs[1:], resolution=CW / (40 / 3))      # 13.333 in wide
    print("PDF:", pdf)


if __name__ == "__main__":
    build()
